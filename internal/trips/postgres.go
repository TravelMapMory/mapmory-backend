package trips

import (
	"context"
	"database/sql"
	"errors"
	"fmt"

	"github.com/google/uuid"
)

// PostgresRepository stores trips in PostgreSQL using a shared connection pool.
// The caller owns the pool and is responsible for closing it.
type PostgresRepository struct {
	db *sql.DB
}

// NewPostgresRepository constructs a repository without opening a new pool.
func NewPostgresRepository(db *sql.DB) *PostgresRepository {
	return &PostgresRepository{db: db}
}

var _ Repository = (*PostgresRepository)(nil)

// Create inserts a trip for a trusted application user. IDs and timestamps
// are generated by PostgreSQL according to the existing schema.
func (r *PostgresRepository) Create(ctx context.Context, ownerID uuid.UUID, title, notes string) (Trip, error) {
	const query = `
		INSERT INTO trips (owner_id, title, notes)
		VALUES ($1, $2, $3)
		RETURNING id, owner_id, title, notes, created_at
	`

	var trip Trip
	err := r.db.QueryRowContext(ctx, query, ownerID, title, notes).Scan(
		&trip.ID, &trip.OwnerID, &trip.Title, &trip.Notes, &trip.CreatedAt,
	)
	if err != nil {
		return Trip{}, fmt.Errorf("create trip: %w", err)
	}
	return trip, nil
}

// ListByOwner returns the requesting user's trips in newest-first order.
// The ID tie-breaker ensures a deterministic order for equal timestamps.
func (r *PostgresRepository) ListByOwner(ctx context.Context, ownerID uuid.UUID) ([]Trip, error) {
	const query = `
		SELECT id, owner_id, title, notes, created_at
		FROM trips
		WHERE owner_id = $1
		ORDER BY created_at DESC, id DESC
	`

	rows, err := r.db.QueryContext(ctx, query, ownerID)
	if err != nil {
		return nil, fmt.Errorf("list trips: %w", err)
	}
	defer rows.Close()

	trips := make([]Trip, 0)
	for rows.Next() {
		var trip Trip
		if err := rows.Scan(&trip.ID, &trip.OwnerID, &trip.Title, &trip.Notes, &trip.CreatedAt); err != nil {
			return nil, fmt.Errorf("scan trip list: %w", err)
		}
		trips = append(trips, trip)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterate trip list: %w", err)
	}
	return trips, nil
}

// GetByID returns only a trip owned by ownerID. A missing trip and a trip
// owned by someone else both return ErrNotFound, without revealing existence.
func (r *PostgresRepository) GetByID(ctx context.Context, ownerID, tripID uuid.UUID) (Trip, error) {
	const query = `
		SELECT id, owner_id, title, notes, created_at
		FROM trips
		WHERE id = $1 AND owner_id = $2
	`

	var trip Trip
	err := r.db.QueryRowContext(ctx, query, tripID, ownerID).Scan(
		&trip.ID, &trip.OwnerID, &trip.Title, &trip.Notes, &trip.CreatedAt,
	)
	if errors.Is(err, sql.ErrNoRows) {
		return Trip{}, ErrNotFound
	}
	if err != nil {
		return Trip{}, fmt.Errorf("get trip: %w", err)
	}
	return trip, nil
}
